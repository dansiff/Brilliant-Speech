export function getExerciseIllustration(label: string): string {
  const normalizedLabel = label.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase();
  return EXERCISE_ILLUSTRATIONS.find(([keywords]) =>
    keywords.some(keyword => normalizedLabel.includes(keyword))
  )?.[1] ?? '🗣️';
}
